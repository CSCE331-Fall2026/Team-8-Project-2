CREATE TYPE order_status AS ENUM ('paid', 'canceled', 'refunded');
CREATE TYPE payment_method AS ENUM ('credit_card', 'debit_card', 'cash', 'gift_card', 'meal_pass');
CREATE TYPE storage_type AS ENUM ('freezer', 'refrigerator', 'pantry');
CREATE TYPE combo_type AS ENUM ('Bowl', 
    'Plate', 
    'Bigger Plate', 
    'A la carte', 
    'Drink', 
    'Bowl Combo', 
    'Plate Combo', 
    'Bigger Plate Combo',
    'Appetizer');
CREATE TYPE menu_item_type AS ENUM ('entree',
    'side',
    'appetizer',
    'drink');

CREATE TABLE orders (
    order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status order_status DEFAULT 'paid',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ,
    payment_method payment_method,
    order_total FLOAT DEFAULT 0.0
);

CREATE TABLE combos (
    combo_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_name combo_type,
    combo_price FLOAT DEFAULT 0.0
);

CREATE TABLE menu_items (
    menu_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_name VARCHAR(50),
    premium_charge FLOAT DEFAULT 0.0,
    active BOOLEAN DEFAULT TRUE,
    menu_item_type menu_item_type
);

CREATE TABLE ingredients (
    ingredient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_name VARCHAR(50),
    quantity_in_stock FLOAT,
    storage_type storage_type,
    ingredient_cost FLOAT,
    expiry_date TIMESTAMPTZ,
    min_qty_on_hand FLOAT,
    measurement_units VARCHAR(20),
    shelf_life_days INT
);

CREATE TABLE order_details (
    order_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id INT REFERENCES combos(combo_id),
    order_id INT REFERENCES orders(order_id),
    order_qty INT
);

CREATE TABLE combo_details (
    combo_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id INT REFERENCES menu_items(menu_item_id),
    order_detail_id INT REFERENCES order_details(order_detail_id),
    servings FLOAT
);

CREATE TABLE menu_item_details (
    menu_item_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id INT REFERENCES menu_items(menu_item_id),
    ingredient_id INT REFERENCES ingredients(ingredient_id),
    ingredient_quantity FLOAT
);